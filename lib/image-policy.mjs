// Keep optimizer configuration, admin validation, and rendered image sources aligned.
const builtInOrigins = [
  "https://images.unsplash.com",
  "https://images.openai.com",
];

export function configuredImageOrigins(
  storage = process.env.NEXT_PUBLIC_SUPABASE_URL,
  extra = process.env.IMAGE_CDN_ORIGINS,
) {
  return [
    ...new Set(
      [...builtInOrigins, storage, ...(extra || "").split(",")]
        .filter((value) => typeof value === "string" && value.trim())
        .map((value) => {
          const url = new URL(value.trim());
          if (
            url.protocol !== "https:" &&
            !(
              url.protocol === "http:" &&
              ["127.0.0.1", "localhost"].includes(url.hostname)
            )
          )
            throw new Error("Image origins must use HTTPS");
          if (url.username || url.password)
            throw new Error("Image origins cannot contain credentials");
          return url.origin;
        }),
    ),
  ];
}

export function imageSourceAllowed(value, origins = configuredImageOrigins()) {
  if (typeof value !== "string" || !value || /[\\\u0000-\u0020]/.test(value))
    return false;
  if (value.startsWith("/") && !value.startsWith("//")) return true;
  try {
    const url = new URL(value);
    // File-picker previews are local browser object URLs and bypass optimization.
    if (url.protocol === "blob:")
      return ["http:", "https:"].includes(new URL(url.pathname).protocol);
    return !url.username && !url.password && origins.includes(url.origin);
  } catch {
    return false;
  }
}

export function renderedImageOrigins() {
  // The explicit public variable is generated by next.config.mjs for client bundles.
  return process.env.NEXT_PUBLIC_IMAGE_ORIGINS
    ? JSON.parse(process.env.NEXT_PUBLIC_IMAGE_ORIGINS)
    : configuredImageOrigins();
}
